        switch language {
        case .system:
            let preferred = Locale.preferredLanguages.first ?? "en"
            languageCode = preferred.hasPrefix("nl") ? "nl" : "en"
        case .english:
            languageCode = "en"
        case .dutch:
            languageCode = "nl"
        }
    }

    static func t(_ english: String, _ args: [CVarArg]) -> String {
        let template: String
        if languageCode == "nl", let dutch = dutch[english] {
            template = dutch
        } else {
            template = english
        }
        guard !args.isEmpty else { return template }
        return String(format: template, arguments: args)
